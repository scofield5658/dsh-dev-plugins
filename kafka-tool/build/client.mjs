/**
 * Build the browser artifact `client.js` from `src/client.js`.
 *
 * The Harness loads plugin bundles as classic scripts: one file that registers a
 * lazy factory through `window.__ModuleLoader__.load({ id, factory })`, where the
 * factory receives the host module-table `require`. esbuild bundles the source
 * (including `react-resizable-panels`) with the module table as externals, and
 * this script wraps that bundle back into the registration envelope, so the
 * factory body still runs only at materialization.
 *
 * `--check` builds in memory and fails when the committed `client.js` differs.
 */
import { build } from 'esbuild'
import { readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)))
const manifest = JSON.parse(await readFile(path.join(root, 'package.json'), 'utf8'))
const target = path.join(root, 'client.js')

// Platform singletons the host module table serves; everything else is inlined.
const EXTERNAL = ['react', 'react-dom', 'react-dom/client', 'react/jsx-runtime']

const result = await build({
  entryPoints: [path.join(root, 'src', 'client.js')],
  bundle: true,
  write: false,
  format: 'cjs',
  platform: 'browser',
  target: ['chrome120'],
  // Unminified so the committed artifact stays reviewable and debuggable.
  minify: false,
  // Bundling may rename colliding identifiers; tests look components up by name.
  keepNames: true,
  legalComments: 'none',
  external: EXTERNAL,
  logLevel: 'warning',
})

// The bundle is embedded as-is: re-indenting would alter multi-line template literals.
const artifact = `/* Generated by build/client.mjs from src/client.js. Do not edit by hand. */
window.__ModuleLoader__.load({
  id: ${JSON.stringify(manifest.name)},
  factory(require) {
    var module = { exports: {} };
    var exports = module.exports;
${result.outputFiles[0].text.trim()}
    return module.exports.factory(require);
  },
});
`

if (process.argv.includes('--check')) {
  const committed = await readFile(target, 'utf8').catch(() => '')
  if (committed !== artifact) {
    console.error(`${manifest.name}: client.js is out of date with src/client.js; run \`pnpm build\` and commit the result`)
    process.exit(1)
  }
  console.log(`${manifest.name}: client.js is up to date`)
} else {
  await writeFile(target, artifact)
  console.log(`${manifest.name}: client.js (${artifact.length} B)`)
}
